#!/usr/bin/env python3
"""Generate SKILLS.md — the machine- and human-readable catalog of every skill."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILLS = os.path.join(ROOT, "skills")
OUT = os.path.join(ROOT, "SKILLS.md")
SKIP = {"_shared"}

TRACK_TITLES = {
    "00-orchestration": "00 — Orchestration & Methodology",
    "01-recon": "01 — Reconnaissance & Attack Surface",
    "02-vuln-class": "02 — Vulnerability Classes",
    "03-platform": "03 — Platform & Technology",
    "04-framework": "04 — Frameworks",
    "05-protocol": "05 — Protocols",
    "06-post-exploitation": "06 — Post-Exploitation & Pivoting",
    "07-supply-chain": "07 — Supply Chain & CI/CD",
    "08-ai-llm": "08 — AI / LLM Applications",
    "09-reporting": "09 — Reporting & Disclosure",
    "10-opsec": "10 — Operator Security",
    "99-engineering": "99 — Engineering (non-offensive)",
}


def parse(path):
    """Parse frontmatter with PyYAML so quoting/escaping is handled correctly.

    Reading the raw line leaves the YAML quotes in place ('like this') and breaks
the catalog. Fall back to a naive parser only when PyYAML is unavailable.
    """
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}
    try:
        import yaml
        loaded = yaml.safe_load(parts[1])
        if isinstance(loaded, dict):
            return {str(k): ("" if v is None else (", ".join(map(str, v)) if isinstance(v, list) else str(v)))
                    for k, v in loaded.items()}
    except Exception:
        pass
    fm = {}
    for line in parts[1].splitlines():
        m = re.match(r"^([A-Za-z_]+):\s*(.*)$", line.rstrip())
        if m:
            fm[m.group(1)] = m.group(2).strip().strip("'\"")
    return fm


def main():
    rows = {}
    for dirpath, dirnames, filenames in os.walk(SKILLS):
        dirnames[:] = [d for d in dirnames if d not in SKIP]
        if "SKILL.md" not in filenames:
            continue
        path = os.path.join(dirpath, "SKILL.md")
        fm = parse(path)
        track = fm.get("track") or "99-engineering"
        name = os.path.basename(dirpath)
        rows.setdefault(track, []).append((name, fm))

    total = sum(len(v) for v in rows.values())
    out = [
        "# Skill Catalog",
        "",
        f"**{total} skills.** Generated by `tools/build_catalog.py` — do not edit by hand.",
        "",
        "Load order suggestion: read `skills/_shared/SKILL-FORMAT.md` once, then the",
        "`_shared/evidence-policy.md` and `_shared/scope-gate.md` policies apply to every skill.",
        "",
    ]
    for track in sorted(rows):
        out.append(f"## {TRACK_TITLES.get(track, track)}")
        out.append("")
        out.append("| Skill | When to use | Severity ceiling | Requires |")
        out.append("|---|---|---|---|")
        for name, fm in sorted(rows[track]):
            desc = fm.get("description", "").replace("|", "\\|")
            desc = desc.split("Triggers:")[0].strip().rstrip(".")
            if len(desc) > 190:
                desc = desc[:187] + "..."
            sev = fm.get("severity_ceiling", "-")
            req = fm.get("requires", "[]").strip("[]").strip()
            out.append(f"| [`{name}`](skills/{name}/) | {desc} | {sev} | {req or '—'} |")
        out.append("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {OUT} with {total} skills across {len(rows)} tracks")


if __name__ == "__main__":
    main()
